"""Build-provenance: VERSION parsing, boot logging, /api/health, and the
build_sha stamp on every trade.

The ledger is paisa-exact but was, until now, recording trades from a build we
could not identify. These tests pin the whole chain: deploy writes
backend/VERSION -> the app reads it at import -> every Trade row carries the
commit that produced it.
"""
from __future__ import annotations

import datetime as dt

import pytest
from sqlalchemy import create_engine, text
from sqlalchemy.orm import Session

from app.core import version as ver


# ── VERSION file parsing ────────────────────────────────────────────────────

VERSION_BODY = (
    "commit=2b3356d\n"
    "branch=feat/exec-completeness\n"
    "deployed_at=2026-07-28T04:30:00Z\n"
    "deployed_by=priyanshusaraf@mac\n"
)


def _write(tmp_path, body):
    p = tmp_path / "VERSION"
    p.write_text(body)
    return p


def test_parses_commit_and_metadata(tmp_path):
    info = ver.parse_version_file(_write(tmp_path, VERSION_BODY))
    assert info["commit"] == "2b3356d"
    assert info["branch"] == "feat/exec-completeness"
    assert info["deployed_by"] == "priyanshusaraf@mac"


def test_tolerates_blank_lines_comments_and_whitespace(tmp_path):
    body = "\n# generated by deploy.sh\n  commit = abc1234  \n\nbranch=main\n"
    info = ver.parse_version_file(_write(tmp_path, body))
    assert info["commit"] == "abc1234"
    assert info["branch"] == "main"


def test_dirty_sha_is_preserved_not_normalised(tmp_path):
    """deploy.sh refuses dirty trees, but if a -dirty SHA ever reaches the app
    we record it verbatim rather than silently cleaning it — an untraceable
    build must look untraceable in the ledger."""
    info = ver.parse_version_file(_write(tmp_path, "commit=abc1234-dirty\n"))
    assert info["commit"] == "abc1234-dirty"


def test_missing_file_returns_empty_not_raise(tmp_path):
    assert ver.parse_version_file(tmp_path / "nope") == {}


def test_unparseable_file_returns_empty_not_raise(tmp_path):
    assert ver.parse_version_file(_write(tmp_path, "\x00\x01 garbage no equals\n")) == {}


def test_file_without_commit_key_is_treated_as_unusable(tmp_path):
    assert ver.parse_version_file(_write(tmp_path, "branch=main\n")) == {}


# ── loud failure, never a silent null ───────────────────────────────────────

def test_missing_version_logs_an_error(tmp_path, monkeypatch, caplog):
    monkeypatch.setattr(ver, "_VERSION_PATH", tmp_path / "absent")
    ver.reset_cache()
    with caplog.at_level("ERROR"):
        assert ver.get_build_sha() == ver.UNKNOWN
    assert any("VERSION" in r.message for r in caplog.records), \
        "a missing VERSION must be loud at boot, not a silent null stamp"


def test_unparseable_version_logs_an_error(tmp_path, monkeypatch, caplog):
    monkeypatch.setattr(ver, "_VERSION_PATH", _write(tmp_path, "garbage\n"))
    ver.reset_cache()
    with caplog.at_level("ERROR"):
        assert ver.get_build_sha() == ver.UNKNOWN
    assert any("VERSION" in r.message for r in caplog.records)


def test_unresolvable_build_is_unknown_never_none(tmp_path, monkeypatch):
    """NULL in trades.build_sha means "row predates the column". A running process
    that cannot read its VERSION is a different fact and must not borrow that
    meaning, or "never recorded" and "recorded as unidentifiable" become the same
    query result."""
    monkeypatch.setattr(ver, "_VERSION_PATH", tmp_path / "absent")
    ver.reset_cache()
    assert ver.get_build_sha() is not None
    assert ver.get_build_sha() == "unknown"


def test_unknown_sentinel_cannot_be_mistaken_for_a_sha():
    """A short SHA is lowercase hex; the sentinel must not be parseable as one."""
    with pytest.raises(ValueError):
        int(ver.UNKNOWN, 16)


def test_good_version_does_not_log_an_error(tmp_path, monkeypatch, caplog):
    monkeypatch.setattr(ver, "_VERSION_PATH", _write(tmp_path, VERSION_BODY))
    ver.reset_cache()
    with caplog.at_level("ERROR"):
        assert ver.get_build_sha() == "2b3356d"
    assert not [r for r in caplog.records if "VERSION" in r.message]


def test_read_is_cached_so_every_trade_insert_is_not_a_file_read(tmp_path, monkeypatch):
    p = _write(tmp_path, VERSION_BODY)
    monkeypatch.setattr(ver, "_VERSION_PATH", p)
    ver.reset_cache()
    assert ver.get_build_sha() == "2b3356d"
    p.write_text("commit=deadbee\n")          # changed on disk mid-process
    assert ver.get_build_sha() == "2b3356d"   # still the booted build
    ver.reset_cache()
    assert ver.get_build_sha() == "deadbee"


