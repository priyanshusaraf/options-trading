# ── the stamp itself ────────────────────────────────────────────────────────

def _make_trade(**kw):
    from app.db.models import Trade
    base = dict(
        instrument_key="NIFTY", direction="long", option_type="CE",
        tradingsymbol="NIFTY26JUL24000CE", exchange="NFO", strike=24000.0,
        expiry=dt.date(2026, 7, 30), qty=75,
        entry_premium=100.0, entry_cost=7500.0, entry_spot=24000.0,
        entry_time=dt.datetime(2026, 7, 28, 9, 30),
        exit_premium=160.0, exit_charges=20.0, exit_spot=24100.0,
        exit_time=dt.datetime(2026, 7, 28, 9, 45), exit_reason="TARGET",
        gross_pnl=4500.0, charges_total=20.0, net_pnl=4480.0,
        return_pct=0.6, holding_minutes=15.0, win=True,
    )
    base.update(kw)
    return Trade(**base)


def test_new_trade_is_stamped_with_the_running_build(tmp_path, monkeypatch):
    from app.db.models import Base

    monkeypatch.setattr(ver, "_VERSION_PATH", _write(tmp_path, VERSION_BODY))
    ver.reset_cache()

    eng = create_engine(f"sqlite:///{tmp_path / 'stamp.db'}")
    Base.metadata.create_all(eng)
    with Session(eng) as s:
        s.add(_make_trade())
        s.commit()
        assert s.query(type(_make_trade())).one().build_sha == "2b3356d"


def test_trade_stamp_is_unknown_when_version_is_absent(tmp_path, monkeypatch):
    """No VERSION => 'unknown', never a guess and never NULL.

    NULL is reserved for rows that predate the column. This row was written by a
    live process, so it must say so — the useful query is
    `WHERE build_sha = 'unknown'`, which finds engines that deployed outside
    deploy.sh, and that query is impossible if these rows are NULL."""
    from app.db.models import Base, Trade

    monkeypatch.setattr(ver, "_VERSION_PATH", tmp_path / "absent")
    ver.reset_cache()

    eng = create_engine(f"sqlite:///{tmp_path / 'nostamp.db'}")
    Base.metadata.create_all(eng)
    with Session(eng) as s:
        s.add(_make_trade())
        s.commit()
        assert s.query(Trade).one().build_sha == "unknown"


def test_the_orm_cannot_write_a_null_build_sha(tmp_path, monkeypatch):
    """Passing build_sha=None explicitly still stamps 'unknown'.

    SQLAlchemy treats an explicit None as "not supplied" and applies the column
    default. That is the behaviour we want and it is load-bearing: NULL is
    reserved for rows the *migration* left alone, so no code path that books a
    trade can manufacture one. Pinned because it is surprising — the obvious
    reading of `Trade(build_sha=None)` is that it writes a NULL."""
    from app.db.models import Base, Trade

    monkeypatch.setattr(ver, "_VERSION_PATH", tmp_path / "absent")
    ver.reset_cache()

    eng = create_engine(f"sqlite:///{tmp_path / 'nonull.db'}")
    Base.metadata.create_all(eng)
    with Session(eng) as s:
        s.add(_make_trade(build_sha=None))
        s.commit()
        assert s.query(Trade).one().build_sha == "unknown"


def test_null_and_unknown_are_distinguishable_in_one_table(tmp_path, monkeypatch):
    """The whole point of the sentinel: a pre-migration row and an unidentifiable
    build must be separable by a query, not collapsed onto the same value.

    The NULL row is inserted the way real ones exist — a legacy row that the
    migration added the column to — not via the ORM, which by design cannot
    produce one (see the test above)."""
    import app.db.session as sess_mod
    from app.db.models import Base

    monkeypatch.setattr(ver, "_VERSION_PATH", tmp_path / "absent")
    ver.reset_cache()

    db = tmp_path / "mixed.db"
    eng = create_engine(f"sqlite:///{db}")
    with eng.begin() as c:                      # a production-shaped legacy row
        c.execute(text(_legacy_trades_ddl()))
        c.execute(text("INSERT INTO trades (id, tradingsymbol) VALUES (1, 'SUZLON')"))
    monkeypatch.setattr(sess_mod, "engine", eng)
    sess_mod._migrate_schema()                  # adds build_sha, leaves it NULL
    Base.metadata.create_all(eng)

    with Session(eng) as s:
        s.add(_make_trade(id=2))                        # running, unidentifiable
        s.add(_make_trade(id=3, build_sha="2b3356d"))   # identified
        s.commit()

    with eng.begin() as c:
        pre = c.execute(text("SELECT COUNT(*) FROM trades WHERE build_sha IS NULL")).scalar()
        unk = c.execute(text("SELECT COUNT(*) FROM trades WHERE build_sha = 'unknown'")).scalar()
        known = c.execute(text("SELECT COUNT(*) FROM trades WHERE build_sha = '2b3356d'")).scalar()
    assert (pre, unk, known) == (1, 1, 1)


