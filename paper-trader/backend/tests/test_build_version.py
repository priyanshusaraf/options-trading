def test_health_reports_unknown_build_without_failing(monkeypatch, tmp_path):
    from fastapi.testclient import TestClient
    from app.main import app

    monkeypatch.setattr(ver, "_VERSION_PATH", tmp_path / "absent")
    ver.reset_cache()
    with TestClient(app) as c:
        r = c.get("/api/health")
    assert r.status_code == 200          # health must not go red on a missing VERSION
    # Same sentinel the ledger stamps, so health and trades.build_sha can never
    # disagree about what this process is. deploy.sh compares this to the SHA it
    # shipped, and "unknown" fails that comparison — which is the intent.
    assert r.json()["build"]["commit"] == "unknown"


# ── the migration, against a production-shaped DB ───────────────────────────

def _legacy_trades_ddl() -> str:
    """The trades table WITHOUT build_sha — i.e. what production has today."""
    return """
    CREATE TABLE trades (
        id INTEGER NOT NULL PRIMARY KEY,
        instrument_key VARCHAR(32), direction VARCHAR(8), option_type VARCHAR(4),
        tradingsymbol VARCHAR(64), exchange VARCHAR(8), segment VARCHAR(16),
        strategy_key VARCHAR(64), strike FLOAT, expiry DATE, qty INTEGER,
        entry_premium FLOAT, entry_cost FLOAT, entry_spot FLOAT, entry_time DATETIME,
        exit_premium FLOAT, exit_charges FLOAT, exit_spot FLOAT, exit_time DATETIME,
        exit_reason VARCHAR(32), gross_pnl FLOAT, charges_total FLOAT, net_pnl FLOAT,
        return_pct FLOAT, holding_minutes FLOAT, win BOOLEAN, mode VARCHAR(8)
    )
    """


def _cols(conn, table="trades"):
    return {r[1] for r in conn.execute(text(f"PRAGMA table_info({table})"))}


def test_migration_adds_build_sha_to_a_pre_migration_table(tmp_path, monkeypatch):
    """Against a DB shaped like production (34 real trades, no build_sha)."""
    import app.db.session as sess_mod

    db = tmp_path / "legacy.db"
    eng = create_engine(f"sqlite:///{db}")
    with eng.begin() as c:
        c.execute(text(_legacy_trades_ddl()))
        c.execute(text(
            "INSERT INTO trades (id, tradingsymbol, net_pnl, mode) "
            "VALUES (1, 'SUZLON', 417.40, 'live')"))
        assert "build_sha" not in _cols(c)

    monkeypatch.setattr(sess_mod, "engine", eng)
    sess_mod._migrate_schema()

    with eng.begin() as c:
        assert "build_sha" in _cols(c)
        row = c.execute(text("SELECT tradingsymbol, net_pnl, build_sha FROM trades")).one()
    assert row[0] == "SUZLON"          # existing row survives
    assert row[1] == 417.40            # paisa-exact value untouched
    assert row[2] is None              # historic trades are honestly unknown


def test_migration_is_idempotent(tmp_path, monkeypatch):
    """init_db runs on every boot — a second pass must not raise 'duplicate column'."""
    import app.db.session as sess_mod

    eng = create_engine(f"sqlite:///{tmp_path / 'idem.db'}")
    with eng.begin() as c:
        c.execute(text(_legacy_trades_ddl()))
    monkeypatch.setattr(sess_mod, "engine", eng)

    sess_mod._migrate_schema()
    sess_mod._migrate_schema()          # must be a no-op, not an error
    sess_mod._migrate_schema()

    with eng.begin() as c:
        assert "build_sha" in _cols(c)


def test_migration_does_not_touch_a_table_it_has_no_additions_for(tmp_path, monkeypatch):
    """Guard against the ALTER loop running on a table that create_all hasn't made."""
